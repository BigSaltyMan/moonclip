#!/usr/bin/env python3
"""Generate a complete reference batch or check it without touching the baseline."""
import argparse
from pathlib import Path
import os
import subprocess
import sys
import tempfile
import time
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/conformance"))
from compare import (Invalid, canonical_bytes, compare, decode, load, metrics,
                     read_manifest, require, sha256, validate_geometry, validate_result)


def invoke_oracle(command, request, case_id, timeout):
    try:
        process = subprocess.run(command, input=request, capture_output=True, timeout=timeout)
    except subprocess.TimeoutExpired as error:
        raise Invalid(f"{case_id}: oracle timed out after {timeout} seconds") from error
    except OSError as error:
        raise Invalid(f"{case_id}: oracle launch failed: {error}") from error
    require(process.returncode == 0, case_id, f"oracle exited {process.returncode}: " + process.stderr.decode('utf-8', errors='replace')[:400])
    response = decode(process.stdout, case_id + ".oracle")
    validate_geometry(response, case_id + ".oracle")
    return response


def verified_binary(root):
    work = root / ".tmp/oracle"
    binary = work / "build" / ("moonclip-oracle.exe" if os.name == "nt" else "moonclip-oracle")
    report = load(work / "build/environment.json")
    require(binary.is_file(), "oracle", "missing built executable; run scripts/build_oracle.sh")
    for field, path in (("binary_sha256", binary), ("adapter_sha256", root / "tools/oracle/adapter.cpp"),
                        ("lock_sha256", root / "tools/oracle/upstream-lock.json"),
                        ("cmake_sha256", root / "tools/oracle/CMakeLists.txt")):
        require(report.get(field) == sha256(path.read_bytes()), "oracle", f"{field} mismatch; rebuild verified tool")
    return binary


def generate(root, manifest, mode, command, timeout=20):
    lock, records = read_manifest(root, manifest, require_expected=(mode == "check"), strict=True)
    started = time.monotonic()
    work = root / ".tmp/oracle"
    work.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="reference-", dir=work) as temp:
        stage = Path(temp) / "expected"
        stage.mkdir()
        for entry, case, digest, baseline in records:
            cid = case["case_id"]
            response = invoke_oracle(command, (root / entry["input"]).read_bytes(), cid, timeout)
            response["input_sha256"] = digest
            response["metrics"] = metrics(response)
            validate_result(response, case, digest, lock, cid)
            encoded = canonical_bytes(response)
            (stage / (cid + ".json")).write_bytes(encoded)
            if mode == "check":
                compare(baseline, response, cid)
                require(encoded == (root / entry["expected"]).read_bytes(), cid, "regenerated bytes differ despite geometry match")
        report = {"mode": mode, "case_count": len(records), "oracle_commit": lock["commit"],
                  "seconds": round(time.monotonic()-started, 3)}
        (work / "generation-report.json").write_bytes(canonical_bytes(report))
        if mode == "write":
            # Publish only after the entire batch succeeds. Roll back a failed rename.
            destination = root / ("testdata/offset/expected" if records[0][1]["operation"] == "OffsetPolygons" else "testdata/upstream/expected")
            backup = Path(temp) / "previous"
            existed = destination.exists()
            if existed:
                destination.replace(backup)
            try:
                stage.replace(destination)
            except OSError:
                if existed:
                    backup.replace(destination)
                raise
    print(f"Reference {mode}: {len(records)} cases generated by fixed C++ Clipper2; compatibility not run")
    return len(records)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=ROOT / "testdata/manifest.json")
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--check", action="store_true")
    modes.add_argument("--write", action="store_true")
    parser.add_argument("--timeout", type=float, default=20)
    args = parser.parse_args()
    require(0 < args.timeout <= 300, "timeout", "expected (0, 300] seconds")
    # Validate inputs before requiring a build or starting a process.
    read_manifest(ROOT, args.manifest.resolve(), require_expected=args.check, strict=True)
    binary = verified_binary(ROOT)
    generate(ROOT, args.manifest.resolve(), "check" if args.check else "write", [str(binary)], args.timeout)
    return 0

if __name__ == "__main__":
    try:
        sys.exit(main())
    except (Invalid, OSError) as error:
        print(f"reference generation: {error}", file=sys.stderr)
        sys.exit(1)
