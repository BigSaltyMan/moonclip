"""Ordered complete geometry and reports; runner links inputs and hashes only."""
import argparse
from simplify_compare import simplify_selection
from generate_boolean import paths,formatted
from generate_decimal import paths_d
from selection import ROOT

def invocation(c):
    options='options=@moonclip.SimplifyOptions::new(epsilon='+repr(float(c['epsilon']))+',mode=@moonclip.'+c['mode']+')'
    if c['operation']=='Simplify64':return '@moonclip.simplify_paths('+paths(c['paths'])+','+options+')'
    return '@moonclip.Precision::new('+str(c['precision'])+').bind(fn(p){@moonclip.simplify_paths_d('+paths_d(c['paths'])+',precision=p,'+options+')})'

def generated():
    _,records=simplify_selection(ROOT)
    tests=['// Generated by generate_simplify.py; ordered vertices and complete reports.']
    runner=['// Generated inputs / parameters / hashes only. NO expected outputs.','///|','fn run_simplify_cases() -> Array[Json] { [']
    fields=('removed_vertices','removed_per_path','input_degenerate_indices','degenerate_indices','collapsed_indices')
    for _,c,d,v in records:
        decimal=c['operation']=='SimplifyD';scale=(1,10,100,1000,10000,100000,1000000)[c.get('precision',0)]
        tests+=['///|','// Input SHA256: '+d,'test "reference simplify paths: '+c['case_id']+'" {','guard '+invocation(c)+' is Ok(actual) else {fail("Simplify execution failed")}']
        actual='decimal_test_grid(actual.paths(),'+str(scale)+'.0)' if decimal else 'actual.paths()'
        tests+=['assert_eq('+actual+','+paths(v['paths'])+')']
        for field in fields:tests+=['assert_eq(actual.'+field+'(),'+str(v[field])+')']
        tests+=['}']
        fn='simplify_json_d' if decimal else 'simplify_json'
        mapped=invocation(c)+'.map(fn(value){'+fn+'(value'+(','+str(scale)+'.0' if decimal else '')+')})'
        runner+=['actual_simplify_case("'+c['case_id']+'","'+d+'","'+c['operation']+'","'+c['mode']+'",'+str(c.get('precision',0))+','+mapped+'),']
    return {'conformance/simplify_test.mbt':'\n'.join(tests)+'\n','cmd/conformance/simplify_cases.mbt':'\n'.join(runner+[']','}'])+'\n'}

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,text in generated().items():
        data=formatted(text);p=ROOT/name
        if args.check:
            if p.read_bytes()!=data:raise SystemExit('Stale generated simplify data: '+name)
        else:p.write_bytes(data)
    print('Simplify selection: Integer80 + DecimalGrid144 =224 ordered paths and reports; '+('check passed' if args.check else 'generated'))
