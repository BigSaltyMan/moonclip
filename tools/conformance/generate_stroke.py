"""Generate stroke assertions plus a separate inputs/hashes-only runner."""
import argparse
from stroke_compare import stroke_selection
from generate_boolean import paths,formatted
from selection import ROOT


def call(case):
    return '@moonclip.stroke_polyline('+paths([case['path']])[1:-1]+','+repr(float(case['width']))+',cap=@moonclip.CapType::'+case['cap_type']+',options=@moonclip.OffsetOptions::new(join=@moonclip.JoinType::'+case['join_type']+',miter_limit='+repr(float(case['miter_limit']))+',arc_tolerance='+repr(float(case['arc_tolerance']))+'))'


def generated():
    _,records=stroke_selection(ROOT)
    tests=['// Generated by tools/conformance/generate_stroke.py; do not edit.']
    runner=['// Generated original inputs/hashes only; stroke expectations are NOT linked.','///|','fn run_stroke_cases() -> Array[Json] {','[']
    for e,c,digest,expected in records:
        tests+=['///|','// Input SHA256: '+digest,'test "reference stroke paths: '+c['case_id']+'" {','assert_eq('+call(c)+'.map(canonical_paths),Ok(canonical_paths('+paths(expected['paths'])+')))','}']
        runner+=['actual_offset_case("'+c['case_id']+'","'+digest+'",'+call(c)+'),']
    return {'conformance/stroke_test.mbt':'\n'.join(tests)+'\n','cmd/conformance/stroke_cases.mbt':'\n'.join(runner+[']','}'])+'\n'}


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,text in generated().items():
        expected=formatted(text);target=ROOT/name
        if args.check:
            if target.read_bytes()!=expected:raise SystemExit('Generated stroke data is stale: '+name)
        else:target.write_bytes(expected)
    print('Stroke selection: 276 public paths; '+('check passed' if args.check else 'generated'))
