"""220 tests and a separate raw inputs/parameters/hashes-only decimal runner."""
import argparse
from decimal_compare import decimal_selection
from generate_boolean import paths,formatted
from selection import ROOT

def paths_d(value):
    return '['+','.join('['+','.join('@moonclip.PointD::new('+repr(float(x))+','+repr(float(y))+')' for x,y in p)+']' for p in value)+']'

def invocation(case):
    precision='precision=p'
    if case['operation']=='BooleanD':
        call='@moonclip.boolean_op_d('+paths_d(case['subject'])+','+paths_d(case['clip'])+',@moonclip.'+case['clip_type']+','+precision+',fill_rule=@moonclip.'+case['fill_rule']+')'
    else:
        options='options=@moonclip.OffsetOptions::new(join=@moonclip.JoinType::'+case['join_type']+',miter_limit='+repr(float(case['miter_limit']))+',arc_tolerance='+repr(float(case['arc_tolerance']))+')'
        if case['operation']=='OffsetD':call='@moonclip.offset_polygons_d('+paths_d(case['paths'])+','+repr(float(case['delta']))+','+precision+',fill_rule=@moonclip.'+case['fill_rule']+','+options+')'
        else:call='@moonclip.stroke_polyline_d('+paths_d([case['path']])[1:-1]+','+repr(float(case['width']))+','+precision+',cap=@moonclip.CapType::'+case['cap_type']+','+options+')'
    return '@moonclip.Precision::new('+str(case['precision'])+').bind(fn(p){'+call+'})'

def generated():
    _,records=decimal_selection(ROOT)
    tests=['// Generated by generate_decimal.py; exact grid AND exact decoded coordinate checks.','///|\nfn decimal_test_grid(value : @moonclip.PathsD,scale : Double) -> @moonclip.Paths64 raise {\n value.map(fn(path) raise {\n  path.map(fn(point) raise {\n   let x=decimal_test_integer(point.x*scale)\n   let y=decimal_test_integer(point.y*scale)\n   assert_eq(point.x,x.to_double()/scale)\n   assert_eq(point.y,y.to_double()/scale)\n   if point.x==0.0 {assert_true(1.0/point.x>0.0)}\n   if point.y==0.0 {assert_true(1.0/point.y>0.0)}\n   @moonclip.Point64::new(x,y)\n  })\n })\n}\n///|\nfn decimal_test_integer(value : Double) -> Int64 {\n let whole=value.to_int64()\n let fraction=value-whole.to_double()\n if fraction>=0.5 {whole+1L}else if fraction <= -0.5 {whole-1L}else{whole}\n}\n']
    runner=['// Generated original decimal inputs/parameters/hashes only; NO expectations.','///|','fn run_decimal_cases() -> Array[Json] { [']
    scales=(1,10,100,1000,10000,100000,1000000)
    for e,c,d,v in records:
        tests+=['///|','// Complete input SHA256: '+d,'test "reference decimal paths: '+c['case_id']+'" {','guard '+invocation(c)+' is Ok(actual) else {fail("Decimal execution failed")}','assert_eq(canonical_paths(decimal_test_grid(actual,'+str(scales[c['precision']])+'.0)),canonical_paths('+paths(v['grid_paths'])+'))','}']
        runner+=['actual_decimal_case("'+c['case_id']+'","'+d+'","'+c['operation']+'","'+c['reference_route']+'",'+str(c['precision'])+','+invocation(c)+'),']
    return {'conformance/decimal_test.mbt':'\n'.join(tests)+'\n','cmd/conformance/decimal_cases.mbt':'\n'.join(runner+[']','}'])+'\n'}

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    for name,text in generated().items():
        expected=formatted(text);target=ROOT/name
        if args.check:
            if target.read_bytes()!=expected:raise SystemExit('Stale generated decimal data: '+name)
        else:target.write_bytes(expected)
    print('Decimal selection: 220 public paths (196 DecimalGrid +24 ClipperDCommonGrid); '+('check passed' if args.check else 'generated'))
