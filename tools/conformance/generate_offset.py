"""Generate locked offset tests and an inputs-only native runner."""
import argparse
from offset_compare import offset_selection
from generate_boolean import paths, formatted
from selection import ROOT


def call(case):
    return '@moonclip.offset_polygons('+paths(case['paths'])+','+repr(float(case['delta']))+',fill_rule=@moonclip.'+case['fill_rule']+',options=@moonclip.OffsetOptions::new(join=@moonclip.'+case['join_type']+',miter_limit='+repr(float(case['miter_limit']))+'))'


def generated():
    _,records=offset_selection(ROOT)
    tests=['// Generated by tools/conformance/generate_offset.py; do not edit.']
    runner=['// Generated inputs only; expected offset geometry is NOT linked.','///|','fn run_offset_cases() -> Array[Json] {','[']
    for entry,case,digest,expected in records:
        tests+=['///|','// Input SHA256: '+digest,'test "reference offset paths: '+case['case_id']+'" {','assert_eq('+call(case)+'.map(canonical_paths), Ok(canonical_paths('+paths(expected['paths'])+')))','}']
        runner+=['actual_offset_case("'+case['case_id']+'","'+digest+'",'+call(case)+'),']
    return {'conformance/offset_test.mbt':'\n'.join(tests)+'\n','cmd/conformance/offset_cases.mbt':'\n'.join(runner+[']','}'])+'\n'}


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,text in generated().items():
        expected=formatted(text);target=ROOT/name
        if args.check:
            if target.read_bytes()!=expected:raise SystemExit('Generated offset data is stale: '+name)
        else:target.write_bytes(expected)
    print('Offset selection: 116 public paths; '+('check passed' if args.check else 'generated'))
