"""Generate exact public and private rule tests from the locked reference catalog."""
import argparse
import subprocess
from selection import ROOT, selections
from compare import sha256

def paths(value, prefix='@moonclip.'):
    return '['+','.join('['+','.join(prefix+'Point64::new(%dL,%dL)'%tuple(p) for p in ring)+']' for ring in value)+']'

def call(case, internal=False, tree=False):
    function="boolean_tree_execute" if tree else "boolean_execute"
    public="boolean_tree" if tree else "boolean_op"
    if internal:
        return function+'('+paths(case['subject'],'')+','+paths(case['clip'],'')+','+case['operation']+', {input: Default::default(),max_nodes:500000,max_work:5000000},rule='+case['fill_rule']+')'
    return '@moonclip.'+public+'('+paths(case['subject'])+','+paths(case['clip'])+',@moonclip.'+case['operation']+',fill_rule=@moonclip.'+case['fill_rule']+')'

def tests(records, internal=False):
    prefix='' if internal else '@moonclip.'
    canonical='internal_canonical' if internal else 'canonical_paths'
    lines=['// Generated by tools/conformance/generate_boolean.py; do not edit.']
    for entry,case,digest,expected in records:
        lines+=['///|','// Input SHA256: '+digest,'test "reference '+('internal ' if internal else '')+'paths: '+entry['case_id']+'" {','let result = '+call(case,internal),'assert_eq(result.map('+canonical+'), Ok('+canonical+'('+paths(expected['paths'],prefix)+')))','}']
    return '\n'.join(lines)+'\n'

def tree_value(node,internal=False,depth=1):
    prefix='' if internal else '@moonclip.'
    variant='InternalRefNode' if internal else 'RefNode'
    return variant+'('+str(depth)+','+('true' if depth%2==0 else 'false')+','+paths([node['path']],prefix)[1:-1]+',['+','.join(tree_value(c,internal,depth+1) for c in node['children'])+'])'

def tree_tests(records,internal=False):
    canonical='internal_reference_tree' if internal else 'reference_tree'
    sort='internal_ref_sort' if internal else 'ref_sort'
    lines=['// Generated by tools/conformance/generate_boolean.py; do not edit.']
    for entry,case,digest,expected in records:
        value='['+','.join(tree_value(c,internal) for c in expected['tree']['children'])+']'
        lines+=['///|','// Input SHA256: '+digest,'test "reference '+('internal ' if internal else '')+'tree: '+entry['case_id']+'" {','assert_eq('+call(case,internal,True)+'.map('+canonical+'), Ok('+sort+'('+value+')))','}']
    return '\n'.join(lines)+'\n'

def runner(records):
    lines=['// Generated inputs only; expected geometry is NOT linked into this executable.','///|','fn run_cases() -> Array[Json] {','[']
    for entry,case,digest,_ in records:
        lines.append('actual_case("'+entry['case_id']+'","'+digest+'",'+call(case)+','+call(case,tree=True)+'),')
    return '\n'.join(lines+[']','}'])+'\n'

def formatted(text):
    return subprocess.run(['moonfmt','-'],input=text.encode('utf-8'),stdout=subprocess.PIPE,check=True).stdout.replace(b'\r\n',b'\n')

def generated():
    _,public,internal=selections(ROOT/'testdata/manifest.json')
    return {'conformance/cases_test.mbt':tests(public),'boolean_reference_wbtest.mbt':tests(internal,True),'cmd/conformance/cases.mbt':runner(public),'conformance/tree_test.mbt':tree_tests(public),'boolean_tree_reference_wbtest.mbt':tree_tests(internal,True)}

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,text in generated().items():
        expected=formatted(text);target=ROOT/name
        if args.check:
            if target.read_bytes()!=expected:raise SystemExit('Generated conformance data is stale: '+name)
        else:target.write_bytes(expected)
    print('Boolean selection: 152 public + 48 internal; '+('check passed' if args.check else 'generated'))
