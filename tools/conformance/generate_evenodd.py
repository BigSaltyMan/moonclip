"""Generate the preselected 60 contour tests, exclusively from pinned JSON."""
import json, hashlib, argparse
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def paths(value):
    return '['+','.join('['+','.join('@moonclip.Point64::new(%dL,%dL)'%tuple(p) for p in ring)+']' for ring in value)+']'
def generate():
    m=json.loads((ROOT/'testdata/manifest.json').read_text(encoding='utf-8'))
    selected=json.loads((ROOT/'testdata/evenodd-selection.json').read_text(encoding='utf-8'))
    actual=[e for e in m['cases'] if json.loads((ROOT/e['input']).read_text(encoding='utf-8'))['fill_rule']=='EvenOdd']
    assert [e['case_id'] for e in actual]==selected['case_ids'] and len(actual)==selected['expected_count']==60
    lines=['// Generated by tools/conformance/generate_evenodd.py; do not edit.']
    for entry in actual:
        raw=(ROOT/entry['input']).read_bytes();case=json.loads(raw);expected=json.loads((ROOT/entry['expected']).read_bytes())
        lines += ['///|','// Input SHA256: '+hashlib.sha256(raw).hexdigest(), 'test "reference paths: '+entry['case_id']+'" {', '  let result = @moonclip.boolean_op('+paths(case['subject'])+','+paths(case['clip'])+',@moonclip.'+case['operation']+')', '  assert_eq(result.map(canonical_paths), Ok(canonical_paths('+paths(expected['paths'])+')))', '}']
    return '\n'.join(lines)+'\n'

def runner():
    manifest=json.loads((ROOT/'testdata/manifest.json').read_text(encoding='utf-8'))
    lines=['// Generated inputs only; expected geometry is NOT linked into this executable.', '///|', 'fn run_cases() -> Array[Json] {', '  [']
    for e in manifest['cases']:
        raw=(ROOT/e['input']).read_bytes();c=json.loads(raw)
        if c['fill_rule']!='EvenOdd':continue
        lines.append('actual_case("'+e['case_id']+'","'+hashlib.sha256(raw).hexdigest()+'",@moonclip.boolean_op('+paths(c['subject'])+','+paths(c['clip'])+',@moonclip.'+c['operation']+')),')
    return '\n'.join(lines+['  ]','}'])+'\n'

def formatted(text):
    import subprocess
    return subprocess.run(['moonfmt','-'],input=text.encode('utf-8'),stdout=subprocess.PIPE,check=True).stdout.replace(b"\r\n",b"\n")

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    files={'conformance/cases_test.mbt':generate(),'cmd/conformance/cases.mbt':runner()}
    for name,text in files.items():
        expected=formatted(text);target=ROOT/name
        if args.check:
            if target.read_bytes()!=expected: raise SystemExit('Generated conformance data is stale: '+name)
        else:target.write_bytes(expected)
    print('Generated EvenOdd selection: 60 cases; check passed' if args.check else 'Generated 60 EvenOdd cases')
